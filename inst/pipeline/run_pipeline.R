# run_pipeline.R -------------------------------------------------------------
# CanPAS curation pipeline entry point: runs the steps in order, with pre-flight
# checks, a log and an exit code.
#
# 位置 / location
#   The pipeline ships inside the package as consolidated scripts, one file per
#   step group, under inst/pipeline/ (this directory).  The set is scripts only:
#   no data files are included.  The data root (expression matrices, raw series
#   matrices, processed tables, catalog) is a separate project tree.
#
# 与旧入口的差异 / difference from the original entry point
#   The original pipeline/run_pipeline.R ran one Rscript per step from
#   <project>/pipeline/R/<n>_*.R.  The code is now consolidated, so each step is
#   still run in its own Rscript process (same isolation, same exit-code
#   handling, same log), but the command sources the consolidated file and calls
#   that step's run_*() function.  Step ids, the --list/--check/--from/--to/
#   --only/--dry-run interface and the log format are unchanged.
#
# 用法 / usage:
#   Rscript run_pipeline.R --list                  # list every step
#   Rscript run_pipeline.R --check                 # consistency check only (step 16)
#   Rscript run_pipeline.R --from 07 --to 09       # run a range
#   Rscript run_pipeline.R --only 11,16            # run selected steps
#   Rscript run_pipeline.R --dry-run               # print the commands instead
#
# 前置条件 / prerequisites:
#   CPAS_DATA_ROOT     data root (default /home/Jingle/data/Project/CPAS)
#   CPAS_PIPELINE_DIR  override for the directory holding the consolidated scripts
#                      (default: system.file("pipeline", package = "CanPAS"))
#   CPAS_DB_PASSWORD   mirror password (only the steps flagged needs_db require it;
#                      when it is unset those steps are refused before anything runs)
#   Steps flagged needs_net fetch GEO/CGGA data; steps flagged needs_db write to
#   the MySQL mirror (06/09/13/14/15/17 and the later repair/upload steps).
#
# 说明: per-cohort arguments are still written inside each step script (historical
#       convention); this entry point owns the order, the pre-flight checks and the
#       log, and does not change any step's behaviour.
# 输出: pipeline/out/pipeline_run_log.csv  (under the data root)
# ----------------------------------------------------------------------------

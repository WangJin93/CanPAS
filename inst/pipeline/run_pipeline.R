args <- commandArgs(trailingOnly = TRUE)
get_arg <- function(flag, default = NULL) {
  i <- match(flag, args)
  if (is.na(i) || i == length(args)) return(default)
  args[i + 1L]
}
if ("--help" %in% args || "-h" %in% args) {
  cat("Usage: Rscript run_pipeline.R [--list] [--check] [--from ID] [--to ID]\n",
      "                                   [--only ID,ID] [--dry-run]\n",
      "\n",
      "Runs the CanPAS curation pipeline from the consolidated scripts under\n",
      "inst/pipeline/.  Without --only/--from/--to every listed step is selected;\n",
      "use --dry-run first, and set CPAS_DATA_ROOT to the project tree.\n")
  quit(status = 0)
}
if ("--list" %in% args) {
  print(steps[, c("id", "script", "group", "what", "needs_db", "needs_net")], row.names = FALSE)
  quit(status = 0)
}

selected <- if ("--check" %in% args) {
  "16"
} else if (!is.null(get_arg("--only"))) {
  trimws(strsplit(get_arg("--only"), ",")[[1]])
} else {
  from <- get_arg("--from", steps$id[1]); to <- get_arg("--to", steps$id[nrow(steps)])
  ids <- steps$id
  ids[seq(match(from, ids), match(to, ids))]
}
unknown <- setdiff(selected, steps$id)
if (length(unknown)) stop("Unknown step id(s): ", paste(unknown, collapse = ", "))
sel <- steps[match(selected, steps$id), , drop = FALSE]
cat(sprintf("Pipeline: %d step(s) selected (%s)\n", nrow(sel), paste(sel$id, collapse = ", ")))

dry <- "--dry-run" %in% args
pw <- Sys.getenv("CPAS_DB_PASSWORD", unset = "")
if (!dry && any(sel$needs_db) && !nzchar(pw))
  stop("These steps need the mirror: ", paste(sel$id[sel$needs_db], collapse = ", "),
       ".\nSet CPAS_DB_PASSWORD (see inst/pipeline/Renviron.example).", call. = FALSE)

log_rows <- list()
for (i in seq_len(nrow(sel))) {
  st <- sel[i, ]
  script <- file.path(pipeline_dir, st$group)
  if (!file.exists(script)) {
    log_rows[[length(log_rows) + 1L]] <- data.frame(step = st$id, script = st$script,
      status = "missing script", seconds = NA_real_, stringsAsFactors = FALSE)
    next
  }
  cat(sprintf("\n=== [%s] %s ===\n", st$id, st$what))
  expr <- sprintf("source(%s); %s()", shQuote(script), st$runner)
  cmd <- sprintf("Rscript -e %s", shQuote(expr))
  if (dry) { cat("  would run:", cmd, "\n"); next }
  t0 <- Sys.time()
  status <- tryCatch({
    code <- system(cmd, ignore.stdout = FALSE, ignore.stderr = FALSE)
    if (identical(code, 0L)) "ok" else paste0("exit ", code)
  }, error = function(e) paste("error:", conditionMessage(e)))
  log_rows[[length(log_rows) + 1L]] <- data.frame(
    step = st$id, script = st$script, status = status,
    seconds = round(as.numeric(difftime(Sys.time(), t0, units = "secs")), 1),
    stringsAsFactors = FALSE)
  if (!identical(status, "ok") && st$id %in% c("16"))
    cat("  check step reported problems (exit code set by the script)\n")
}
if (!dry && length(log_rows)) {
  res <- do.call(rbind, log_rows)
  out <- file.path(root, "pipeline/out/pipeline_run_log.csv")
  dir.create(dirname(out), showWarnings = FALSE, recursive = TRUE)
  if (file.exists(out)) res <- rbind(utils::read.csv(out, stringsAsFactors = FALSE), res)
  utils::write.csv(res, out, row.names = FALSE)
  cat("\n=== pipeline summary ===\n"); print(res, row.names = FALSE)
  cat("log:", out, "\n")
  bad <- res$status[!res$status %in% c("ok")]
  if (length(bad)) quit(status = 1) else quit(status = 0)
}
